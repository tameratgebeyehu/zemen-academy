import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const katexRoot = join(root, 'node_modules', 'katex', 'dist');
let css = readFileSync(join(katexRoot, 'katex.min.css'), 'utf8');
css = css.replace(/font-display:block/g, 'font-display:swap');

css = css.replace(/url\(fonts\/([^)]+\.woff2)\)/g, (_match, filename) => {
  const encoded = readFileSync(join(katexRoot, 'fonts', filename)).toString('base64');
  return `url(data:font/woff2;base64,${encoded})`;
});
css = css.replace(/,url\(fonts\/[^)]+\.woff\) format\("woff"\),url\(fonts\/[^)]+\.ttf\) format\("truetype"\)/g, '');

const output = join(root, 'src', 'utils', 'katexCss.generated.ts');
writeFileSync(output, `// Generated by scripts/generate-katex-css.mjs. Do not edit manually.\nexport const KATEX_CSS = ${JSON.stringify(css)};\n`);
console.log(`Generated ${output} (${Buffer.byteLength(css)} bytes of embedded offline CSS and fonts).`);
